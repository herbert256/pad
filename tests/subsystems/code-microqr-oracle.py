"""Optional independent decoder: pip install numpy zxing-cpp; run with Python 3.
Zint matrix fixtures were generated by --barcode=MICROQR --dump --vers=N
--secure=1/2/3 [--mask=0/1/2/3] at the revision recorded in microqr.md.
"""
from pathlib import Path
import json
import random
import subprocess
import numpy as np
import zxingcpp

root = Path(__file__).resolve().parents[2]
fixtures = json.loads((Path(__file__).parent / 'fixtures/microqr-zint.json').read_text())
cases = [{'text':f['text'], 'options':f['options']} for f in fixtures]
rng = random.Random(20261102)
for i in range(500):
    mode, alphabet, maximum = rng.choice([
        ('numeric','0123456789',35),('alnum','ABCDEFGHIJKLMNOPQRSTUVWXYZ $%*+-./:',21),
        ('byte','abcdefghijklmnopqrstuvwxyz',15),('kanji','漢字日本語東京',9)])
    text = ''.join(rng.choice(alphabet) for _ in range(rng.randint(1, maximum)))
    cases.append({'text':text, 'options':{'version':'M4','level':'L','mode':mode,'mask':rng.randrange(4)}})
php = "define('PAD',$argv[1].'/pad/'); require PAD.'subs/codes/_lib/microqr.php'; $out=[]; foreach(json_decode(stream_get_contents(STDIN),true) as $c) $out[]=padMicroQrEncode($c['text'],$c['options']); echo json_encode($out,JSON_THROW_ON_ERROR);"
process = subprocess.run(['php','-r',php,str(root)], input=json.dumps(cases), text=True, capture_output=True, check=True)
if process.stderr:
    raise RuntimeError(process.stderr)
results = json.loads(process.stdout)
for i, (case, code) in enumerate(zip(cases, results)):
    if not isinstance(code, dict):
        raise AssertionError((i, code))
    if i < len(fixtures):
        assert [''.join(map(str,r)) for r in code['matrix']] == fixtures[i]['matrix']
    # Explicit two-module quiet zone; 2x, 4x and 8x module sizes cover compact/label output.
    for scale in (2, 4, 8):
        data = np.pad(np.asarray(code['matrix'], dtype=np.uint8), 2)
        pixels = np.repeat(np.repeat((1-data)*255, scale, axis=0), scale, axis=1)
        decoded = zxingcpp.read_barcode(pixels, formats=zxingcpp.BarcodeFormat.MicroQRCode)
        assert decoded is not None and decoded.text == case['text'], (i, scale, case, decoded)
print(f'Micro QR: {len(cases)} payloads, {len(cases)*3} independent ZXing decodes passed')
