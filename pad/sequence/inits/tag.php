<?php

  // Opens a tag-driven run: records that the parameters are to be read from the level rather
  // than from $pqSetParms, and flags the level as a sequence tag so handling/handling.php
  // leaves its options alone - the sequence subsystem consumes them itself.

  $pqEntry          = 'tag';
  $padTagSeq [$pad] = TRUE;

  // A sequence tag is named as its entry in start/tags/ is written: asked of a file system that
  // ignores case, {Keep '1..10', prime} found tags/keep.php and ran as make - ten primes - and
  // {Resume reverse} ended the request on a PHP include error, where a Linux server has no tag
  // named Keep. The prefixed forms are named exactly in padTypeSeq (lib/type.php).

  if ( $padType [$pad] == 'pad' and ! isset ( pqNames ( PQ . 'start/tags' ) [ $padTag [$pad] . '.php' ] ) )
    padError ( "there is no tag named '" . $padTag [$pad] . "'" );

?>
