<?php

  // Live reload's stamp is the newest time of the files behind the pages. A node_modules
  // directory - the packages npm installs under _frontend/ for a Vite build - is none of
  // them and is passed over, as a name starting with a dot is: walked on every poll, its
  // tens of thousands of files cost a tenth of a second of the server's time for every open
  // tab, every second. A file saved beside it still counts.

  include_once PAD . 'exits/_lib/reload.php';

  $nmRoot = sys_get_temp_dir () . '/padReload' . padRandomString ( 8 );
  $nmTime = 1700000000;

  foreach ( [ 'index.pad', '_frontend/main.js', '_frontend/node_modules/vue/index.js' ] as $nmFile ) {
    @mkdir ( dirname ( "$nmRoot/$nmFile" ), 0777, TRUE );
    file_put_contents ( "$nmRoot/$nmFile", 'x' );
  }

  foreach ( [ 'index.pad', '_frontend/main.js', '_frontend/node_modules/vue/index.js',
              '_frontend/node_modules/vue', '_frontend/node_modules', '_frontend', '' ] as $nmFile )
    touch ( rtrim ( "$nmRoot/$nmFile", '/' ), $nmTime );

  touch ( "$nmRoot/_frontend/node_modules/vue/index.js", $nmTime + 500 );
  clearstatcache ();

  $nmInstalled = padReloadNewest ( $nmRoot ) - $nmTime;

  touch ( "$nmRoot/_frontend/main.js", $nmTime + 100 );
  clearstatcache ();

  $nmSaved = padReloadNewest ( $nmRoot ) - $nmTime;

  foreach ( [ '_frontend/node_modules/vue/index.js', '_frontend/main.js', 'index.pad' ] as $nmFile )
    @unlink ( "$nmRoot/$nmFile" );

  foreach ( [ '_frontend/node_modules/vue', '_frontend/node_modules', '_frontend', '' ] as $nmFile )
    @rmdir ( rtrim ( "$nmRoot/$nmFile", '/' ) );

?>
