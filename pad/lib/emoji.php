  // Emoji by shortcode - the {emoji} tag and the emoji pipe.
  //
  //   {emoji 'rocket'}               <span class="pad-emoji" role="img" aria-label="rocket">🚀</span>
  //   {emoji ':tada:', label='Party!'}
  //   {$comment | emoji}             every :shortcode: of the text as its emoji
  //
  // The shortcodes are GitHub's and Slack's - :+1:, :heart:, :rocket:, :white_check_mark: -
  // a few hundred of the common ones, with their aliases. Each comes with the label a screen
  // reader says, the emoji's name: an emoji alone is a picture, and role="img" with an
  // aria-label makes it one with a name instead of a character read out by its code.
  //
  // padEmoji         [ emoji, label ] of a shortcode, colons or not, any case; NULL when
  //                  there is none
  // padEmojiSuggest  the known shortcode nearest to an unknown one, for the error
  // padEmojiHtml     the emoji in its labelled span
  // padEmojiText     a text with each :shortcode: it knows replaced by the emoji itself -
  //                  an unknown one, or a time of day like 10:30:00, stays as it is
  //
  // An emoji that has a text form as well - ❤ ☀ ✔ - carries the variation selector that
  // asks for the colour picture; the people at work are joined with zero width joiners.

  function padEmoji ( $code ) {

    $code = strtolower ( trim ( (string) $code ) );

    if ( strlen ( $code ) > 2 and $code [0] == ':' and substr ( $code, -1 ) == ':' )
      $code = substr ( $code, 1, -1 );

    return padEmojiTable () [$code] ?? NULL;

  }

  function padEmojiSuggest ( $code ) {

    $code = trim ( strtolower ( trim ( (string) $code ) ), ':' );
    $best = '';
    $near = PHP_INT_MAX;

    foreach ( array_keys ( padEmojiTable () ) as $known ) {

      $distance = levenshtein ( $code, (string) $known );

      if ( strlen ( $code ) > 2 and str_contains ( (string) $known, $code ) )
        $distance = min ( $distance, 2 );

      if ( $distance < $near ) {
        $near = $distance;
        $best = (string) $known;
      }

    }

    return ( $near <= max ( 2, intdiv ( strlen ( $code ), 3 ) ) ) ? $best : '';

  }

  function padEmojiHtml ( $emoji, $label ) {

    return '<span class="pad-emoji" role="img" aria-label="' . padChartAttr ( $label ) . '">' . $emoji . '</span>';

  }

  function padEmojiText ( $text ) {

    return preg_replace_callback ( '/:([a-z0-9_+\-]+):/i', function ( $match ) {

      $found = padEmoji ( $match [1] );

      return $found ? $found [0] : $match [0];

    }, (string) $text );

  }

